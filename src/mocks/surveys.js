export const surveyOf = (code) => surveys[code] ?? null

/*
 * 응답. 환자 · 시점(사전/사후) · 설문 코드로 갈린다.
 * 같은 환자가 같은 설문을 사전과 사후에 각각 한 번씩 하므로 시점이 키에 들어간다.
 *
 * 메모(`mocks/notes.js`)와 같은 자리다 — 감정평가 화면에서만 쓰이므로
 * 공유 상태 둘(`dragState`·`scheduleState`)에 합류시키지 않았다.
 */
const responses = reactive({})

const keyOf = (patientId, phase, code) => `${patientId}:${phase}:${code}`

export function responseOf(patientId, phase, code) {
  return responses[keyOf(patientId, phase, code)] ?? null
}

/* 아직 시작하지 않았으면 빈 응답을 만들어 준다 */
export function draftOf(patientId, phase, code) {
  const key = keyOf(patientId, phase, code)
  if (!responses[key]) responses[key] = { answers: {}, done: false, score: null }
  return responses[key]
}

/*
 * 임시 저장. 응답은 이미 반응형 상태에 남아 있지만, **저장했다는 사실이
 * 남아야** 감정평가 목록에서 '작성 중'과 '아직 손대지 않음'을 구분할 수 있다.
 * 오토세이브가 없다는 규칙(3.6절)을 화면에서도 지키는 자리다.
 */
export function saveSurveyDraft(patientId, phase, code) {
  const draft = draftOf(patientId, phase, code)
  const d = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  draft.savedAt = `${pad(d.getHours())}:${pad(d.getMinutes())}`
  return draft
}

export function scoreOf(survey, answers) {
  return survey.questions.reduce((sum, _, i) => sum + (answers[i] ?? 0), 0)
}

/*
 * 제출은 명시적 조작이다. 되돌리기(재작성)도 같은 자리에서 한다 —
 * 오토세이브가 없으므로 임시 저장과 제출이 갈린다.
 */
export function submitSurvey(patientId, phase, code) {
  const survey = surveys[code]
  const draft = draftOf(patientId, phase, code)
  draft.score = scoreOf(survey, draft.answers)
  draft.done = true
  return draft
}

/*
 * 결과 등급. 프로그램 처방 화면의 배지가 이것을 쓴다.
 *
 * ⚠️ Figma 4건(PCL-5 42/80 고위험 · CAPS-5 20/40 고위험 · GAD-7 8/21 중증도 ·
 *    WHOQOL 60/100 정상)에서 **역산한 규칙**이다 — 컷오프를 넘겼는지와
 *    핵심/보조 중 무엇인지 둘로 갈린다. 실제 판정 기준은 척도마다 다르므로
 *    확인이 필요하다(6.2절).
 */
export function gradeOf(survey, score) {
  /* 값이 없는 것을 '정상'으로 두면 안 한 것과 괜찮은 것이 같아 보인다 */
  if (score === null || score === undefined) return '미작성'
  if (!survey.cutoff || score < survey.cutoff) return '정상'
  return survey.role === '핵심' ? '고위험' : '중증도'
}

/* 미응답 문항 수. 제출 가능 여부와 진행률이 같은 값을 본다 */
export function answeredCount(survey, answers) {
  return survey.questions.filter((_, i) => answers[i] !== undefined).length
}
